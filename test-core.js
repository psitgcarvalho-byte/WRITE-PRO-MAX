const b=C.toBlocks(proj,{refs:true});
t('blocos', b.some(x=>x.t==='h1'&&x.x.startsWith('Capítulo 1'))&&b.some(x=>x.t==='h2'&&x.x==='1.1 S')&&b.some(x=>x.t==='h3'&&x.x==='1.1.2 Segunda')&&b.some(x=>x.t==='ref'));
t('sem tags', !b.some(x=>/\[\[/.test(x.x)));
t('system', C.buildSystem({author:'A',targets:T,style:'curto',samples:['x']}).includes('700 e 1100'));
console.log(ok+' ok, '+bad+' falhas'); process.exit(bad?1:0);
