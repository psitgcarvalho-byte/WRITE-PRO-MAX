t('parse', p.titulo==='X'&&p.texto.includes('### A')&&p.refs.length===1);
const q=C.parseResponse('<TITULO>X</TITULO><TEXTO>\n### A\ncortado');
t('parse truncado', q.texto.includes('cortado'));
const ch=C.parseRoteiro('# Capítulo 1: Origens\n- Mito e logos\n2) Sofistas\n# Cap 2\nAristóteles');
t('roteiro', ch.length===2&&ch[0].title==='Origens'&&ch[0].sections.length===2&&ch[0].sections[1].ponto==='Sofistas'&&ch[1].sections[0].ponto==='Aristóteles');
const big=('lorem ipsum dolor '.repeat(2000))+' alvoespecial verdade '.repeat(20)+('foo bar baz '.repeat(2000));
const r=C.rankChunks(big,'verdade alvoespecial',3000);
t('rank', r.includes('alvoespecial')&&r.length<=3200);
