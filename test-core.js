const C=require('./core.js');
let ok=0,bad=0; const t=(n,c)=>{c?ok++:(bad++,console.log('FALHOU',n))};
const filler='palavra '.repeat(80);
const raw=`### Primeira\n${filler}[[CIT]]Segundo Plutarco, em suas Vidas, narra algo importante e [[DIR]]“a vida sem exame não vale a pena”[[/DIR]] como se sabe.[[/CIT]]\n\n[[ANE]]Conta-se que Diógenes pediu a Alexandre que saísse da frente do sol.[[/ANE]]\n\n### Segunda\n${filler}`;
